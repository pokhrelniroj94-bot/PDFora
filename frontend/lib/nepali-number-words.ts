export function nepaliNumberWords(value: number): string {
  if (!Number.isSafeInteger(value) || value < 0 || value > 999_999_999) {
    throw new Error("Enter a whole number from 0 to 99,99,99,999.");
  }
  if (value < 100) return small[value];
  for (const [unit, label] of [[10_000_000, "करोड"], [100_000, "लाख"], [1_000, "हजार"], [100, "सय"]] as const) {
    if (value >= unit) {
      const quotient = Math.floor(value / unit);
      const remainder = value % unit;
      return nepaliNumberWords(quotient) + " " + label + (remainder ? " " + nepaliNumberWords(remainder) : "");
    }
  }
  return small[value];
}
